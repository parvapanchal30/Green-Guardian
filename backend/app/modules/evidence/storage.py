"""Object-storage port for evidence (photos).

The application only ever talks to `ObjectStore`. A provider (local disk now; an S3-compatible adapter later) is
selected by `STORAGE_PROVIDER` through the registry below, exactly like the weather providers. Adding a provider =
implement the protocol, `register_store("key", factory)`; nothing in the service, API or schema changes.

Keys are generated by the server (`{workspace}/{asset}/{evidence-id}.{ext}`), never from user input, and every store
must still refuse keys that could escape its root.
"""

from __future__ import annotations

import os
import re
import tempfile
from collections.abc import Callable
from functools import lru_cache
from pathlib import Path
from typing import Protocol

from app.core.config import Settings, get_settings


class StorageError(Exception):
    """The store could not read or write (disk full, permission, provider outage)."""


class ObjectNotFound(StorageError):
    pass


class ObjectStore(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete(self, key: str) -> None: ...
    def exists(self, key: str) -> bool: ...


_SAFE_KEY = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*(/[A-Za-z0-9][A-Za-z0-9._-]*)*$")


def _check_key(key: str) -> None:
    if not _SAFE_KEY.match(key) or ".." in key:
        raise StorageError(f"unsafe storage key {key!r}")


class MemoryObjectStore:
    """Tests only: no persistence. `fail_puts`/`fail_gets` let tests simulate a provider outage."""

    def __init__(self) -> None:
        self.objects: dict[str, tuple[bytes, str]] = {}
        self.fail_puts = False
        self.fail_gets = False

    def put(self, key: str, data: bytes, content_type: str) -> None:
        _check_key(key)
        if self.fail_puts:
            raise StorageError("simulated outage")
        self.objects[key] = (data, content_type)

    def get(self, key: str) -> bytes:
        _check_key(key)
        if self.fail_gets:
            raise StorageError("simulated outage")
        try:
            return self.objects[key][0]
        except KeyError:
            raise ObjectNotFound(key) from None

    def delete(self, key: str) -> None:
        _check_key(key)
        self.objects.pop(key, None)

    def exists(self, key: str) -> bool:
        _check_key(key)
        return key in self.objects


class LocalFileStore:
    """Files under a root directory. Writes are atomic (temp file + rename) so a crash never leaves a partial image."""

    def __init__(self, root: str | Path) -> None:
        self.root = Path(root).resolve()
        self.root.mkdir(parents=True, exist_ok=True)

    def _path(self, key: str) -> Path:
        _check_key(key)
        path = (self.root / key).resolve()
        if not path.is_relative_to(self.root):  # defence in depth on top of the key pattern
            raise StorageError(f"key {key!r} escapes the storage root")
        return path

    def put(self, key: str, data: bytes, content_type: str) -> None:
        path = self._path(key)
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".upload-")
            try:
                with os.fdopen(fd, "wb") as fh:
                    fh.write(data)
                os.replace(tmp, path)
            except BaseException:
                Path(tmp).unlink(missing_ok=True)
                raise
        except OSError as exc:
            raise StorageError(f"could not write {key}: {exc}") from exc

    def get(self, key: str) -> bytes:
        path = self._path(key)
        try:
            return path.read_bytes()
        except FileNotFoundError:
            raise ObjectNotFound(key) from None
        except OSError as exc:
            raise StorageError(f"could not read {key}: {exc}") from exc

    def delete(self, key: str) -> None:
        try:
            self._path(key).unlink(missing_ok=True)
        except OSError as exc:
            raise StorageError(f"could not delete {key}: {exc}") from exc

    def exists(self, key: str) -> bool:
        return self._path(key).is_file()


StoreFactory = Callable[[Settings], ObjectStore]

_FACTORIES: dict[str, StoreFactory] = {
    "local": lambda s: LocalFileStore(s.storage_local_dir),
    "memory": lambda s: MemoryObjectStore(),
}


class UnknownStorageProvider(ValueError):
    pass


def register_store(key: str, factory: StoreFactory) -> None:
    _FACTORIES[key] = factory


def available_stores() -> list[str]:
    return sorted(_FACTORIES)


def build_store(settings: Settings) -> ObjectStore:
    try:
        factory = _FACTORIES[settings.storage_provider]
    except KeyError:
        raise UnknownStorageProvider(
            f"STORAGE_PROVIDER={settings.storage_provider!r} is not registered; available: {available_stores()}"
        ) from None
    return factory(settings)


@lru_cache
def get_object_store() -> ObjectStore:
    """FastAPI dependency (overridden in tests)."""
    return build_store(get_settings())
